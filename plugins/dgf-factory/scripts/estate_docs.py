#!/usr/bin/env python3
"""estate_docs.py — the estate's inventory pages, rendered from the validators' own readers (ADR 0032 §3).

Writes — or with --check, compares — `index.md` and one `<workspace>.md` per
workspace into the output folder, a folder under `.dgf-factory/`. Every page
starts with MARKER, and a page that does not is never overwritten
(DOCS_PAGE_NOT_GENERATED). `overview.md` is /dgf-docs's own prose and never
touched. Every page is rendered in memory before the first is written, so a
run that stops while reading the estate or rendering writes nothing. The
writes are not one transaction: a write that fails midway (exit 3) leaves
the pages written before it as written, and the rest as they were. Each page
is written through a temporary file mkstemp creates in the output folder,
then os.replace, so no link planted there can redirect a write.

What a page holds is read by the libraries the validators use, never a second
parser: the workspaces and their counts (inventory_root.py), processes and
workflows (lib/process_checks.py), entities (lib/model.py, and the validators'
XML parser for their relations), the references a process makes
(lib/graph.py, built per application: an application's page shows each
resolved in that application; webasm's lists them as written, since each
application resolves a webasm file in its own workspace), components and forms
(lib/plan.py's artifact names over lib/runner.py's targets) and the role names
the root uses (lib/roles.py — an inventory: nothing in a root declares a role,
knowledge/permissions.md §1). The output is deterministic: sorted, with no
timestamp and no absolute path, so two runs over one root are byte-identical.
Every name read from the estate is escaped for Markdown, its control
characters as report.one_line escapes them.

A workspace named `index` or `overview`, in any case, gets the page
`<name>-workspace.md`. Two workspaces whose page names are one when case is
ignored — `index` and `index-workspace`, or `Zims` and `zims` — are a usage
error (exit 3) before anything is written: one page would overwrite the
other on APFS and NTFS.

Usage:  estate_docs.py --workspaces-root R --out .dgf-factory/docs [--check] [--verbose]

Exit codes (contract, see .ai-factory/rules/base.md):
  0  every page written or current
  1  a page exists without the generated marker (DOCS_PAGE_NOT_GENERATED) — left as it is
  2  warnings: a configuration file could not be read (DOCS_SOURCE_UNREADABLE), or under --check a page
     is missing, differs from its rendering, or is an orphan (DOCS_STALE)
  3  usage error: an --out outside `.dgf-factory/`, a root with no workspace, the validators'
     dependencies missing (DEPENDENCY_MISSING), a malformed knowledge table, a vendored schema the
     validators cannot read, two workspaces on one page name, or a page that could not be rendered
     or written
"""

if __name__ == "__main__":
    from lib import runtime; runtime.use_project_venv()

import os
import sys
import tempfile
import traceback
import urllib.parse
from pathlib import Path

from lib import cli, deps, plan, report, workspace

HEADER = "Estate docs"
MARKER = "<!-- generated by estate_docs.py — /dgf-docs regenerates this page; edits to it are overwritten -->"
INDEX = "index.md"
OVERVIEW = "overview.md"  # /dgf-docs's prose: never written, compared or removed here
RESERVED = (INDEX, OVERVIEW)
RUNTIME_DIR = "runtime"   # .dgf-factory/runtime is the install's, never a docs folder
COUNT_TITLES = (("processes", "Processes"), ("workflows", "Workflows"), ("components", "Components"),
                ("forms", "Forms"), ("settings", "Settings"), ("views", "Views"), ("options", "Options"),
                ("form_scripts", "Form scripts"), ("global_scripts", "Global scripts"),
                ("global_styles", "Global styles"))
PROCESS_FILES = ("process", "multitask")  # the artifacts whose references a process's table lists
RELATION_KINDS = (("extract", "extract (N:1)", "view"), ("relation", "relation (M:N, a database junction table)", None),
                  ("slavegrid", "slavegrid (1:N)", "grid"))
_MARKDOWN = str.maketrans({"\\": "\\\\", "`": "\\`", "|": "\\|", "*": "\\*", "[": "\\[", "]": "\\]",
                           "<": "\\<", ">": "\\>"})


def build_parser():
    parser = cli.parser("estate_docs.py", "Write, or check, the estate's generated inventory pages.")
    parser.add_argument("--workspaces-root", required=True, help="the directory that holds the workspaces")
    parser.add_argument("--out", required=True,
                        help="the pages' folder, root-relative, under .dgf-factory/ (paths.docs)")
    parser.add_argument("--check", action="store_true", help="compare the pages with their rendering; write nothing")
    return parser


# --- inputs ----------------------------------------------------------------------------

def check_inputs(args):
    """(root, out as root-relative text, out folder) — or exit 3 on arguments that name no place to write."""
    root = Path(args.workspaces_root)
    if not root.is_dir():
        report.fail(report.EXIT_USAGE, f"--workspaces-root is not a directory: {args.workspaces_root}")
    root = root.resolve()
    out = args.out[2:] if args.out.startswith("./") else args.out
    out = out.rstrip("/")
    problem = plan.path_problem(out) if out else "is empty"
    if problem:
        report.fail(report.EXIT_USAGE, f"--out takes a folder relative to the workspaces root; `{args.out}` {problem}")
    parts = out.split("/")
    if not plan.is_pipeline(out) or len(parts) < 2 or parts[1] == RUNTIME_DIR:
        report.fail(report.EXIT_USAGE, f"--out `{args.out}` is not a folder of its own under {plan.PIPELINE_DIR}/ "
                                       f"(and not {plan.PIPELINE_DIR}/{RUNTIME_DIR}/, the install's): the pages are "
                                       f"the pipeline's artifacts, never the estate's (ADR 0032 §1)")
    folder = root / out
    pipeline = (root / plan.PIPELINE_DIR).resolve()
    resolved = folder.resolve()
    runtime_dir = pipeline / RUNTIME_DIR
    if pipeline not in resolved.parents or resolved == runtime_dir or runtime_dir in resolved.parents:
        report.fail(report.EXIT_USAGE, f"--out `{args.out}` leads outside {plan.PIPELINE_DIR}/ through a link")
    if folder.exists() and not folder.is_dir():
        report.fail(report.EXIT_USAGE, f"--out `{args.out}` is a file, not a folder")
    report.debug("estate_docs.check_inputs", "inputs", root=root, out=out, check=args.check)
    return root, out, folder


# --- Markdown ----------------------------------------------------------------------------

def md(text):
    """An estate name for a page: one line, its Markdown punctuation escaped, so it can neither break a table nor
    open a link, a code span or an HTML tag."""
    text = "" if text is None else str(text)
    return report.one_line(text).translate(_MARKDOWN) if text else "(empty)"


def table(header, rows):
    """A Markdown table, or `None.` when there are no rows. Cells are already escaped."""
    if not rows:
        return ["None.", ""]
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines + [""]


def page_name(ws):
    return f"{ws}-workspace.md" if f"{ws.casefold()}.md" in RESERVED else f"{ws}.md"


def check_page_names(workspaces):
    """Exit 3 when two workspaces' pages — or one and a reserved page — share a name when case is ignored."""
    taken = {name.casefold(): f"the {name} page" for name in RESERVED}
    for ws in workspaces:
        key = page_name(ws).casefold()
        if key in taken:
            report.fail(report.EXIT_USAGE, f"the workspace `{report.one_line(ws)}` and {taken[key]} would both be "
                                           f"written to {report.one_line(page_name(ws))} (case ignored, as APFS and "
                                           f"NTFS ignore it) — rename one; no page was written")
        taken[key] = f"the workspace `{report.one_line(ws)}`"


def link(ws):
    return f"[{md(ws)}]({urllib.parse.quote(page_name(ws))})"


# --- reading the estate ------------------------------------------------------------------

class Estate:
    """Everything the pages show, read once from the root."""

    def __init__(self, root, rep):
        import inventory_root
        from lib import graph, roles, runner
        self.root, self.rep = root, rep
        self.workspaces, self.others = inventory_root.classify_dirs(root)
        self.apps = workspace.applications(root)
        self.counts = {ws: inventory_root.count_workspace(root, ws) for ws in self.workspaces}
        processes, workflows, configs = runner.targets(root)
        self.processes = sorted(self.rel(p) for p in processes)
        self.workflows = sorted(self.rel(p) for p in workflows)
        self.configs = sorted(self.rel(p) for p in configs)
        self.graphs = {app: graph.build(root, app) for app in self.apps}
        if workspace.BASE_WORKSPACE in self.workspaces:
            # read as written: with no application fixed, a webasm reference is resolved in each of them alike
            self.graphs[None] = graph.build(root, None)
        self.roles = roles.inventory(root)
        self.unreadable = set()
        report.debug("estate_docs.Estate", "read", workspaces=len(self.workspaces), apps=len(self.apps),
                     processes=len(self.processes), workflows=len(self.workflows), configs=len(self.configs))

    def rel(self, path):
        return Path(os.path.relpath(path, self.root)).as_posix()

    def graph_of(self, ws):
        return self.graphs.get(None if ws == workspace.BASE_WORKSPACE else ws)

    def parse(self, rel):
        """The validators' XML tree of a root-relative file, or None — reported once as DOCS_SOURCE_UNREADABLE."""
        from lib import process_checks
        tree = process_checks.parse(self.root / rel)
        if tree is None:
            self.not_read(rel, "does not parse")
        return tree

    def not_read(self, rel, why):
        if rel not in self.unreadable:
            self.unreadable.add(rel)
            self.rep.add("DOCS_SOURCE_UNREADABLE", f"the file {why} — its page lists it as not read", file=rel)


def in_workspace(paths, ws):
    return [rel for rel in paths if rel.split("/")[0] == ws]


# --- one workspace's page --------------------------------------------------------------

def process_sections(estate, ws, resolved):
    from lib import process_checks
    rows, transitions, references = [], [], []
    for rel in in_workspace(estate.processes, ws):
        name = rel.split("/")[3]
        tree = estate.parse(rel)
        if tree is None:
            rows.append([md(name), "not read — the file does not parse", "", md(rel)])
            continue
        process = tree.getroot()
        rows.append([md(name), md(process.get("title") or ""),
                     ", ".join(md(state) for state in process_checks.declared(process)) or "none", md(rel)])
        for label, node in process_checks._state_nodes(process):
            for element, target in process_checks.edges(node):
                by = "timeout" if element.tag == "OnTimeout" else "transition"
                transitions.append([md(name), md(label), md(target), by])
        references += process_references(estate, ws, rel, name, resolved)
    header = ["Process", "Edge", "Reference"] + (["Resolves to", "Status"] if resolved else [])
    lines = ["## Processes", ""] + table(["Process", "Title", "States", "File"], rows)
    lines += ["### Transitions", "", "Each state's transitions and timeouts, in the order the file declares them.", ""]
    lines += table(["Process", "From", "To", "By"], transitions)
    lines += ["### References from processes", "", reference_note(ws, resolved), ""]
    return lines + table(header, sorted(references))


def reference_note(ws, resolved):
    if resolved:
        return (f"Each reference a process or its MultiTask settings make, resolved the engine's way in application "
                f"{md(ws)} (knowledge/reference-graph.md §1–§2).")
    return ("Each reference a process or its MultiTask settings make, as the file writes it, unresolved: a reference "
            "that is not `BASE:` is read in whichever application runs the process, so where it leads depends on the "
            "application (knowledge/process-model.md §2.1).")


def process_references(estate, ws, rel, name, resolved):
    g = estate.graph_of(ws)
    if g is None:
        return []
    folder = "/".join(rel.split("/")[:4]) + "/"
    found = []
    for edge in g.edges:
        node = g.nodes.get(edge.source)
        if not edge.source.startswith(folder) or node is None or node.artifact not in PROCESS_FILES:
            continue
        row = [md(name), md(edge.kind), md(edge.value)]
        if resolved:
            row += [md(edge.target) if edge.target else "—", md(edge.status)]
        found.append(row)
    return found


def workflow_section(estate, ws):
    from lib import graph, process_checks
    rows = []
    for rel in in_workspace(estate.workflows, ws):
        name = graph.artifact_of(rel)[1]
        tree = estate.parse(rel)
        if tree is None:
            rows.append([md(name), "not read", "the file does not parse", md(rel)])
            continue
        steps = sum(1 for sequence in tree.getroot().iter("Sequence") for child in sequence
                    if isinstance(child.tag, str))
        targets = [f"{md(step.get('process') or '')} → {md(step.get('state') or '')}"
                   for step in process_checks.state_steps(tree) if step.get("mode") == process_checks.CHANGE_STATE]
        rows.append([md(name), str(steps), ", ".join(targets) or "none", md(rel)])
    lines = ["## Workflows", "", "Steps are the elements directly inside a `Sequence`, at any depth; a CHANGE_STATE "
             "target is the step's `process` and `state` as written (knowledge/process-model.md §2.6).", ""]
    return lines + table(["Workflow", "Steps", "CHANGE_STATE targets", "File"], sorted(rows))


def entity_section(estate, ws):
    from lib import model
    rows, relations = [], []
    for rel in in_workspace(estate.configs, ws):
        found = plan.artifact(rel)
        if not found or found[0] != "settings":
            continue
        name = found[1]
        tree, entity = estate.parse(rel), model.read_entity(estate.root / rel)
        if tree is None or entity is None:
            if tree is not None:
                estate.not_read(rel, "is not read the way the runtime reads it")
            rows.append([md(name), "not read", "", "", md(rel)])
            continue
        key, fields = entity
        rows.append([md(name), datasource(tree), md(key) if key else "none", str(len(fields)), md(rel)])
        relations += entity_relations(tree, name)
    lines = ["## Entities", "", "The datasource as `settings.xml` names it, the first primary key, and the fields "
             "the runtime binds (knowledge/data-model.md §1).", ""]
    lines += table(["Entity", "Datasource", "Primary key", "Fields", "File"], rows)
    lines += ["### Relations", "", "Each field's `extract`, `relation` and `slavegrid`, as written "
              "(knowledge/data-model.md §3).", ""]
    return lines + table(["Entity", "Field", "Kind", "Table", "View or grid"], relations)


def datasource(tree):
    source = tree.getroot().find("datasource")
    if source is None:
        return "none"
    shown = f"{md(source.get('type') or '')} {md(source.get('name') or '')}"
    return shown + (f" (sqltable {md(source.get('sqltable'))})" if source.get("sqltable") else "")


def entity_relations(tree, entity):
    found = []
    for field in tree.getroot().findall("fields/field"):
        for tag, kind, second in RELATION_KINDS:
            for element in field.findall(tag):
                found.append([md(entity), md(field.get("name") or ""), kind, md(element.get("table") or ""),
                              md(element.get(second) or "") if second else "—"])
    return found


def component_section(estate, ws):
    by_folder = {}
    for rel in in_workspace(estate.configs, ws):
        found = plan.artifact(rel)
        if found and found[0] == "component":
            folder, _, rest = found[1].partition("/")
            by_folder.setdefault(folder, []).append(rest or folder)
    rows = [[md(folder), str(len(names)), ", ".join(md(n) for n in sorted(names))]
            for folder, names in sorted(by_folder.items())]
    lines = ["## Components", "", "Component JSON under `FM/_COMPONENTS/`, grouped by the folder each sits in.", ""]
    return lines + table(["Folder", "Count", "Names"], rows)


def form_section(estate, ws):
    forms = []
    for rel in in_workspace(estate.configs, ws):
        found = plan.artifact(rel)
        if found and found[0] == "form":
            entity, _, form = found[1].partition("/")
            forms.append([md(entity), md(form), md(rel)])
    return ["## Forms", ""] + table(["Entity", "Form", "File"], sorted(forms))


def role_section(estate, ws):
    rows = []
    for name, sources in sorted(estate.roles.items()):
        where = {source: [place for place in places if place[0].split("/")[0] == ws]
                 for source, places in sources.items()}
        shown = ", ".join(f"{md(source)} ×{len(places)}" for source, places in sorted(where.items()) if places)
        if shown:
            rows.append([f'"{md(name)}"', shown])
    lines = ["## Role names", "", "Every role name this workspace's files use, quoted exactly as the runtime tests it "
             "— spaces included. An inventory, not a check: nothing in a workspaces root declares a role "
             "(knowledge/permissions.md §1–§2).", ""]
    return lines + table(["Role name", "Where"], rows)


def counts_row(estate, ws):
    return [str(estate.counts[ws][key]) for key, _ in COUNT_TITLES]


def workspace_page(estate, ws):
    resolved = ws != workspace.BASE_WORKSPACE
    role = "base" if not resolved else "application"
    lines = [MARKER, "", f"# Workspace {md(ws)}", "", f"Role: {role}. Back to the [index]({INDEX}).", ""]
    lines += table([title for _, title in COUNT_TITLES], [counts_row(estate, ws)])
    lines += process_sections(estate, ws, resolved)
    lines += workflow_section(estate, ws) + entity_section(estate, ws) + component_section(estate, ws)
    lines += form_section(estate, ws) + role_section(estate, ws)
    return "\n".join(lines).rstrip("\n") + "\n"


# --- the index -----------------------------------------------------------------------------

def index_page(estate):
    import audit_root
    base = workspace.BASE_WORKSPACE
    rows = [[link(ws), "base" if ws == base else "application"] + counts_row(estate, ws) for ws in estate.workspaces]
    lines = [MARKER, "", "# Estate inventory", "",
             "What the configuration under this workspaces root holds, read by estate_docs.py with the readers the "
             "validators use. Each workspace has a page of its own.", "", "## Workspaces", ""]
    lines += table(["Workspace", "Role"] + [title for _, title in COUNT_TITLES], rows)
    lines += ["## Applications", ""]
    if estate.apps:
        lines += [", ".join(md(app) for app in estate.apps) + f" — each runs with {base} as its base workspace, so "
                  f"a {base} process it runs reads the references that are not `BASE:` in that application "
                  f"(knowledge/process-model.md §2.1).", ""]
    else:
        lines += ["None.", ""]
    if base not in estate.workspaces:
        lines += [f"No `{base}/FM/` is under the root, so a `BASE:` reference reads a base workspace mounted from "
                  f"elsewhere (knowledge/composition-specs.md §1.2).", ""]
    lines += ["## Not workspaces", ""]
    lines += table(["Folder", "Why"], [[md(name), md(why)] for name, why in estate.others])
    lines += ["## How this was read", "",
              "- The counts are inventory_root.py's, over each workspace's files.",
              "- References are listed as each file writes them. An application's page resolves them the engine's way "
              "with that application running; webasm's page does not, since each application resolves a webasm "
              "file in its own workspace (knowledge/reference-graph.md §1–§2).",
              "- Role names are an inventory: nothing in a workspaces root declares a role "
              "(knowledge/permissions.md §1).",
              "- A file that does not parse is listed as not read.",
              f"- A citation such as knowledge/process-model.md §2.1 is a section of dgf-factory's knowledge base, "
              f"installed under {plan.PIPELINE_DIR}/runtime/knowledge/.", "",
              "## Limit", "", "```text", audit_root.LIMIT, "```"]
    return "\n".join(lines) + "\n"


def render(root, rep):
    """{page name: its text} for every page, rendered before anything is written."""
    estate = Estate(root, rep)
    check_page_names(estate.workspaces)
    pages = {INDEX: index_page(estate)}
    for ws in estate.workspaces:
        pages[page_name(ws)] = workspace_page(estate, ws)
    rep.ran("docs-render")
    report.debug("estate_docs.render", "rendered", pages=len(pages), unreadable=len(estate.unreadable))
    return pages


# --- writing and checking ----------------------------------------------------------------

def generated(path):
    """True when `path` is a plain file whose first line is MARKER. A link is never ours to overwrite."""
    if path.is_symlink() or not path.is_file():
        return False
    try:
        with open(path, "rb") as handle:
            first = handle.readline()
    except OSError:
        return False
    return first.decode("utf-8", errors="replace").rstrip("\r\n") == MARKER


def orphans(folder, pages):
    """Generated pages in the folder that no workspace renders now."""
    try:
        names = sorted(entry.name for entry in os.scandir(folder))
    except OSError:
        return []
    return [name for name in names if name.endswith(".md") and name not in pages and name != OVERVIEW
            and generated(folder / name)]


def write(path, text):
    """`text` at `path` through a temporary file mkstemp creates beside it — an unpredictable name, opened
    exclusively, so a link planted in the folder is never written through — then os.replace."""
    fd, name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(text.encode("utf-8"))
        os.chmod(name, 0o666 & ~_umask())  # mkstemp's 0600, widened to what an ordinary write would give
        os.replace(name, path)
    except BaseException:
        if os.path.lexists(name):
            os.unlink(name)
        raise


def _umask():
    mask = os.umask(0)
    os.umask(mask)
    return mask


def settle(folder, out, pages, check, rep, lines):
    """Compare each page with its rendering, and — without --check — write or remove it."""
    if check:
        rep.ran("docs-check")
    elif not folder.is_dir():
        folder.mkdir(parents=True)
    for name, text in sorted(pages.items()):
        path, shown = folder / name, f"{out}/{name}"
        if path.exists() or path.is_symlink():
            if not generated(path):
                rep.add("DOCS_PAGE_NOT_GENERATED", "the page exists without the generated marker on its first line — "
                                                   "left as it is; move it, or delete it so it can be generated",
                        file=shown)
                lines.append(f"PAGE: {shown} kept")
                continue
            if path.read_bytes() == text.encode("utf-8"):
                lines.append(f"PAGE: {shown} unchanged")
                continue
        if check:
            why = "differs from its rendering" if path.exists() else "is missing"
            rep.add("DOCS_STALE", f"the page {why} — a write regenerates it", file=shown)
            lines.append(f"PAGE: {shown} stale")
        else:
            write(path, text)
            lines.append(f"PAGE: {shown} wrote")
    for name in orphans(folder, pages):
        shown = f"{out}/{name}"
        if check:
            rep.add("DOCS_STALE", "a generated page no workspace renders now — a write removes it", file=shown)
            lines.append(f"PAGE: {shown} stale")
        else:
            (folder / name).unlink()
            lines.append(f"PAGE: {shown} removed")


def main(argv):
    args = build_parser().parse_args(argv)
    if args.verbose:
        report.set_verbose()
    root, out, folder = check_inputs(args)
    import inventory_root
    if not inventory_root.classify_dirs(root)[0]:
        report.fail(report.EXIT_USAGE, "ERROR ROOT_NO_WORKSPACE no directory under the root has an exact-case FM/ — "
                                       "there is no workspace to document")
    deps.require()
    from lib import json_validate, knowledge
    rep = report.Report("estate-docs")
    lines = [f"ROOT: {root}"]
    try:
        pages = render(root, rep)
        settle(folder, out, pages, args.check, rep, lines)
    except knowledge.KnowledgeTableError as exc:
        report.fail(report.EXIT_USAGE, f"ERROR KNOWLEDGE_TABLE {exc}")
    except json_validate.UnknownDialect as exc:
        report.fail(report.EXIT_USAGE, f"ERROR SCHEMA_UNSELECTABLE {json_validate.UNKNOWN_DIALECT}{exc}` is not "
                                       f"draft-04 or draft-07 — the installed runtime's defect; no page was written")
    except Exception as exc:  # a page that could not be rendered or written is no finding about the root
        if report.verbose():
            traceback.print_exception(type(exc), exc, exc.__traceback__, file=sys.stderr)
        report.fail(report.EXIT_USAGE, f"estate_docs.py stopped on {type(exc).__name__}: "
                                       f"{report.one_line((str(exc).splitlines() or [''])[0])} — any page written "
                                       f"before it stays written, the rest are as they were; --verbose prints the "
                                       f"traceback")
    return report.render([rep], header=HEADER, lines=lines)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
